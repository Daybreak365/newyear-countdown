package dev.newyear.countdown.ai.script;

import com.google.gson.*;
import dev.newyear.countdown.ai.WishEngine;
import dev.newyear.countdown.ai.script.api.*;
import dev.newyear.countdown.ai.script.lang.*;
import dev.newyear.countdown.ai.script.lang.Values.*;
import java.util.*;
import java.util.regex.*;

/** Version-pinned source imports: callbacks are part of the final script AST, so closure persistence works. */
public final class ContentLibrary {
    private ContentLibrary() {}
    public static final class Definition {
        public String id, owner, description, code;
        public int version;
        public long created;
    }
    private static final Pattern IMPORT=Pattern.compile("(?m)^\\s*//\\s*@use\\s+([a-z0-9_./-]+@[0-9]+)\\s*$");
    public static Definition publish(String owner,String name,String description,String body) {
        if(owner==null||!name.matches("[a-z0-9_-]{1,40}"))throw new IllegalArgumentException("Content requires an owner and a 1..40 character name");
        if(body.length()>24000||body.contains("@use"))throw new IllegalArgumentException("Factory too large or contains nested imports");
        ScriptValidator.primeDocs();
        var result=StaticChecker.check(Parser.parse("function factory(params) {\n"+body+"\n}"),ScriptApi.globalNames(),ScriptApi.HOST_MEMBERS);
        if(!result.ok())throw new IllegalArgumentException(result.issues().toString());
        var definitions=WishEngine.get().state().content;
        long mine=definitions.values().stream().filter(d->owner.equals(d.owner)).count();
        if(mine>=128)throw new IllegalArgumentException("Content library limit reached (128 versions per player)");
        String prefix=owner+"/"+name;int version=definitions.values().stream().filter(d->d.id.startsWith(prefix+"@")).mapToInt(d->d.version).max().orElse(0)+1;
        Definition d=new Definition();d.id=prefix+"@"+version;d.owner=owner;d.description=McUtil.clean(description,400);d.code=body;d.version=version;d.created=System.currentTimeMillis();definitions.put(d.id,d);return d;
    }
    public static String expand(String code,String owner) {
        return expand(code,owner,WishEngine.get().state().content);
    }
    public static String expand(String code,String owner,Map<String,Definition> definitions) {
        if(code.startsWith("// wishai-content-pinned\n"))return code;
        Matcher matcher=IMPORT.matcher(code);StringBuilder prelude=new StringBuilder();Set<String> included=new LinkedHashSet<>();
        while(matcher.find()) {
            String id=matcher.group(1);if(!included.add(id))continue;if(included.size()>8)throw new IllegalArgumentException("At most 8 factory imports");
            Definition d=definitions.get(id);
            if(d==null||!Objects.equals(d.owner,owner))throw new IllegalArgumentException("Unknown or inaccessible content: "+id);
            prelude.append("content.bind(").append(new JsonPrimitive(id)).append(", (params) => {\n").append(d.code).append("\n});\n");
        }
        if(included.isEmpty())return code;
        return "// wishai-content-pinned\n"+prelude+IMPORT.matcher(code).replaceAll("");
    }
    public static ApiObject api(ScriptInstance inst) {
        Map<String,Callable> factories=new LinkedHashMap<>();
        return new ApiObject("content")
            .fn("bind","(id,factory) internal version-pinned factory registration (generated by // @use id@version)",(in,s,a)->{
                String id=Args.str(in,a,0,"id");if(factories.size()>=8&&!factories.containsKey(id))throw in.error("Too many factories");factories.put(id,Args.fn(in,a,1,"factory"));return id;
            })
            .fn("create","(id,params) → factory result. Include // @use exact-id@version in the script. All effects belong to this caller script.",(in,s,a)->{
                String id=Args.str(in,a,0,"id");Callable factory=factories.get(id);if(factory==null)throw in.error("Factory not imported; add // @use "+id);return in.invoke(factory,List.of(Args.opts(a,1)));
            });
    }
}
